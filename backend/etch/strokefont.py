def text_strokes(text: str, x: float, y: float, size: float, rot: int = 0, align: str = "center", mirror: bool = False):
    """Return list of polylines (list of (x,y)) in mm for `text` with cap height `size`, anchored at (x,y)."""
    text = text.upper()
    scale = size / 6.0
    adv = 6.0 * scale  # advance per glyph (5 units + 1 gap)
    width = adv * len(text) - scale
    if align == "center":
        ox = -width / 2
    elif align == "right":
        ox = -width
    else:
        ox = 0.0
    oy = -size / 2
    out = []
    import math
    ca, sa = math.cos(math.radians(rot)), math.sin(math.radians(rot))
    for k, ch in enumerate(text):
        g = GLYPHS.get(ch, GLYPHS["?"])
        for stroke in g:
            pts = []
            for gx, gy in stroke:
                lx = ox + k * adv + gx * scale
                ly = oy + gy * scale
                if mirror:
                    lx = -lx
                px = x + lx * ca - ly * sa
                py = y + lx * sa + ly * ca
                pts.append((px, py))
            if len(pts) >= 2:
                out.append(pts)
    return out
